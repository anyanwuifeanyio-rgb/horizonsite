export interface FlightGeoDistance {
  departureCode: string;
  arrivalCode: string;
  km: number;
  miles: number;
  nauticalMiles: number;
}

/**
 * Calculates Great-Circle flight distance using the Haversine formula
 */
export function calculateFlightDistance(
  depCodeOrStr: string,
  arrCodeOrStr: string
): FlightGeoDistance | null {
  const depMatch = depCodeOrStr?.match(/\b([A-Z]{3})\b/);
  const arrMatch = arrCodeOrStr?.match(/\b([A-Z]{3})\b/);

  const depCode = depMatch ? depMatch[1] : depCodeOrStr?.trim().substring(0, 3).toUpperCase();
  const arrCode = arrMatch ? arrMatch[1] : arrCodeOrStr?.trim().substring(0, 3).toUpperCase();

  if (!depCode || !arrCode) return null;

  const depCoord = AIRPORT_COORDINATES[depCode];
  const arrCoord = AIRPORT_COORDINATES[arrCode];

  if (!depCoord || !arrCoord) return null;

  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const R = 6371; // Earth radius in km

  const dLat = toRad(arrCoord.lat - depCoord.lat);
  const dLng = toRad(arrCoord.lng - depCoord.lng);

  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(depCoord.lat)) *
      Math.cos(toRad(arrCoord.lat)) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);

  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const km = Math.round(R * c);
  const miles = Math.round(km * 0.621371);
  const nauticalMiles = Math.round(km * 0.539957);

  return {
    departureCode: depCode,
    arrivalCode: arrCode,
    km,
    miles,
    nauticalMiles
  };
}
