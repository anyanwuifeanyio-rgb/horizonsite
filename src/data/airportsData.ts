/**
 * Format standard value stored in flightData:
 * e.g. "Lagos (LOS) - Murtala Muhammed Int'l, Nigeria"
 */
export function formatAirportValue(airport: Airport): string {
  return `${airport.city} (${airport.code}) - ${airport.name}, ${airport.country}`;
}

/**
 * Short label for compact display:
 * e.g. "Lagos (LOS) - Nigeria"
 */
export function formatAirportShort(airport: Airport): string {
  return `${airport.city} (${airport.code}) · ${airport.country}`;
}

/**
 * Find airport by 3-letter IATA code
 */
export function findAirportByCode(code: string): Airport | undefined {
  const upper = code.trim().toUpperCase();
  return AIRPORTS.find(a => a.code === upper);
}

/**
 * Find airport matching a full string or search input
 */
export function matchAirportFromString(str: string): Airport | undefined {
  if (!str) return undefined;
  const match = str.match(/\b([A-Z]{3})\b/);
  if (match) {
    const byCode = findAirportByCode(match[1]);
    if (byCode) return byCode;
  }
  const clean = str.toLowerCase();
  return AIRPORTS.find(a => 
    a.city.toLowerCase().includes(clean) || 
    a.name.toLowerCase().includes(clean) ||
    a.country.toLowerCase().includes(clean)
  );
}

// ----------------------------------------------------------------------
// FULL ROUTE FORMATTING UTILITIES (No raw LOS-LHR alone)
// ----------------------------------------------------------------------

/**
 * Returns formatted city, country, and code e.g. "Lagos, Nigeria (LOS)"
 */
export function formatFullCityAirport(codeOrStr: string): string {
  if (!codeOrStr) return '';
  const airport = matchAirportFromString(codeOrStr) || findAirportByCode(codeOrStr);
  if (airport) {
    return `${airport.city}, ${airport.country} (${airport.code})`;
  }
  return codeOrStr;
}

/**
 * Returns full airport name with city and country e.g. "Murtala Muhammed International Airport, Lagos, Nigeria (LOS)"
 */
export function formatFullAirportName(codeOrStr: string): string {
  if (!codeOrStr) return '';
  const airport = matchAirportFromString(codeOrStr) || findAirportByCode(codeOrStr);
  if (airport) {
    return `${airport.name}, ${airport.city}, ${airport.country} (${airport.code})`;
  }
  return codeOrStr;
}

/**
 * Formats a flight route in full written format:
 * e.g. "Lagos, Nigeria (LOS) ➔ London Heathrow, United Kingdom (LHR)"
 */
export function formatFullRoute(fromStr: string, toStr: string, arrow: string = '➔'): string {
  const fromPart = formatFullCityAirport(fromStr);
  const toPart = formatFullCityAirport(toStr);
  return `${fromPart} ${arrow} ${toPart}`;
}

/**
 * Formats detailed flight route with official airport names:
 * e.g. "Murtala Muhammed Int'l (LOS), Lagos, Nigeria to London Heathrow (LHR), London, United Kingdom"
 */
export function formatDetailedFlightRoute(fromStr: string, toStr: string): string {
  const fromAirport = matchAirportFromString(fromStr) || findAirportByCode(fromStr);
  const toAirport = matchAirportFromString(toStr) || findAirportByCode(toStr);
  
  if (fromAirport && toAirport) {
    return `${fromAirport.name} (${fromAirport.code}), ${fromAirport.city}, ${fromAirport.country} to ${toAirport.name} (${toAirport.code}), ${toAirport.city}, ${toAirport.country}`;
  }
  return `${formatFullCityAirport(fromStr)} to ${formatFullCityAirport(toStr)}`;
}

